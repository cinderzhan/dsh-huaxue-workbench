throw new Error('旧宿主补丁安装器已停用。请按仓库根目录 INSTALL.md 安装独立工作台。');
import { readFile, writeFile, mkdir, symlink, access, copyFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const app = process.env.DSH_DESKTOP_APP;
if (!app) throw Error('Set DSH_DESKTOP_APP.');
const profile = path.join(process.env.APPDATA, 'dsh-desktop/harness/profiles/web');
const patches = path.join(project, 'work/workbench-host-patches');
const backup = path.join(project, 'work/workbench-migration-backup');
const require = createRequire(path.join(app, 'package.json'));
const yaml = require('yaml');
const exists = p => access(p).then(() => true, () => false);
const digest = text => createHash('sha256').update(text).digest('hex');
const manifest = JSON.parse(await readFile(path.join(patches, 'manifest.json'), 'utf8'));
const version = JSON.parse(await readFile(path.join(app, 'package.json'), 'utf8')).version;
if (version !== manifest.desktop) throw Error('DSH version changed; rebuild and verify the host patches first.');
for (const record of manifest.records) {
  const sha = digest(await readFile(record.installed));
  if (![record.originalSha256, record.patchedSha256, ...(record.acceptedSha256 || [])].includes(sha)) throw Error('Installed host changed: ' + record.pkg);
}
await mkdir(backup, {recursive:true});
const packageFile = path.join(profile, 'package.json');
const patchFile = path.join(profile, 'cordis.patch.yml');
const packageText = await readFile(packageFile,'utf8');
const patchText = await readFile(patchFile,'utf8');
for (const [name,text] of [['profile-package.json',packageText],['profile-cordis.patch.yml',patchText]]) if (!await exists(path.join(backup,name))) await writeFile(path.join(backup,name),text,{flag:'wx'});
const packages=JSON.parse(packageText), config=yaml.parse(patchText);
if (!Array.isArray(config)) throw Error('Unexpected profile patch structure');
const hostPath=path.join(project,'outputs/dsh-local-workbenches');
await mkdir(path.join(hostPath,'node_modules'),{recursive:true});
for (const [target,link] of [[path.join(app,'node_modules/@deepseek-ai'),path.join(hostPath,'node_modules/@deepseek-ai')],[hostPath,path.join(profile,'node_modules/dsh-local-workbenches')]]) if (!await exists(link)) await symlink(target,link,'junction');
packages.dependencies['dsh-local-workbenches']='link:'+hostPath.replaceAll('\\','/');
packages.dsh ??= {}; packages.dsh.profile ??= {}; packages.dsh.profile.bundles ??= [];
for (const bundle of ['dsh-local-workbenches','dsh-huaxue-workbench']) if (!packages.dsh.profile.bundles.includes(bundle)) packages.dsh.profile.bundles.push(bundle);
if (!config.some(entry=>entry.insert?.some(row=>row.id==='dsh-local-workbenches'))) config.push({insert:[{id:'dsh-local-workbenches',name:'dsh-local-workbenches'}]});
for (const record of manifest.records) await copyFile(path.join(patches,record.pkg+'.patched.js'),record.installed);
await writeFile(packageFile,JSON.stringify(packages,null,2)+'\n');
await writeFile(patchFile,yaml.stringify(config));
console.log(JSON.stringify({installed:true,desktop:version,patches:manifest.records.length,backup,requiresHarnessReload:true}));
